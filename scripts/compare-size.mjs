#!/usr/bin/env node
// Builds both demo apps and reports what each i18n approach costs in bytes:
//   1. Library runtime alone (minified, React external) — the fixed cost.
//   2. The demo app's initial JS — library + app code + bundled English catalog.
//   3. Each lazily loaded locale chunk — JSON (i18next) vs compiled .po (Lingui).
// Writes the result to reports/bundle-size.md.
import { execSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { brotliCompressSync, gzipSync } from "node:zlib";
import { build } from "vite";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const apps = [
  {
    name: "react-i18next",
    dir: "apps/react-i18next-demo",
    // Exactly the runtime APIs the demo app imports.
    runtime: `
      import i18n from "i18next";
      import { initReactI18next, useTranslation, Trans } from "react-i18next";
      import resourcesToBackend from "i18next-resources-to-backend";
      export { i18n, initReactI18next, useTranslation, Trans, resourcesToBackend };
    `,
  },
  {
    name: "Lingui",
    dir: "apps/lingui-demo",
    // Macros compile away; this is what remains at runtime.
    runtime: `
      import { i18n } from "@lingui/core";
      import { I18nProvider, useLingui, Trans } from "@lingui/react";
      export { i18n, I18nProvider, useLingui, Trans };
    `,
  },
];

const sizes = (buf) => ({
  raw: buf.length,
  gzip: gzipSync(buf, { level: 9 }).length,
  brotli: brotliCompressSync(buf).length,
});
const sum = (list) =>
  list.reduce((a, b) => ({ raw: a.raw + b.raw, gzip: a.gzip + b.gzip, brotli: a.brotli + b.brotli }), {
    raw: 0,
    gzip: 0,
    brotli: 0,
  });
const kb = (n) => `${(n / 1024).toFixed(1)} kB`;

async function runtimeSize(app) {
  // A real file inside the app so bare imports resolve against its node_modules.
  const cacheDir = join(root, app.dir, "node_modules/.cache");
  mkdirSync(cacheDir, { recursive: true });
  const entry = join(cacheDir, "size-entry.mjs");
  writeFileSync(entry, app.runtime);
  const result = await build({
    root: join(root, app.dir),
    configFile: false,
    logLevel: "silent",
    // Library mode keeps process.env.NODE_ENV as-is; production apps strip dev-only code.
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
    build: {
      write: false,
      minify: true,
      lib: { entry, formats: ["es"], fileName: "runtime" },
      rollupOptions: { external: ["react", "react-dom", "react/jsx-runtime"] },
    },
  });
  const output = (Array.isArray(result) ? result[0] : result).output;
  return sum(output.filter((c) => c.type === "chunk").map((c) => sizes(Buffer.from(c.code))));
}

function appSizes(app) {
  const dist = join(root, app.dir, "dist");
  const manifest = JSON.parse(readFileSync(join(dist, ".vite/manifest.json"), "utf8"));
  const file = (key) => sizes(readFileSync(join(dist, manifest[key].file)));

  // Initial JS = the HTML entry plus everything it statically imports.
  const initial = new Set();
  const visit = (key) => {
    if (initial.has(key)) return;
    initial.add(key);
    for (const dep of manifest[key].imports ?? []) visit(dep);
  };
  visit(Object.keys(manifest).find((k) => manifest[k].isEntry));

  const locales = {};
  for (const [key, chunk] of Object.entries(manifest)) {
    const m = key.match(/locales\/(pl|ar)\b/);
    if (m && chunk.isDynamicEntry) locales[m[1]] = file(key);
  }
  return { initial: sum([...initial].map(file)), locales };
}

const rows = [];
for (const app of apps) {
  console.log(`Building ${app.name}…`);
  execSync("pnpm exec vite build --logLevel warn", { cwd: join(root, app.dir), stdio: "inherit" });
  rows.push({ app, runtime: await runtimeSize(app), ...appSizes(app) });
}

const line = (label, pick) =>
  `| ${label} | ${rows.map((r) => `${kb(pick(r).gzip)} (${kb(pick(r).raw)} min)`).join(" | ")} |`;

const report = [
  "# Bundle size",
  "",
  `Generated by \`pnpm compare:size\` on ${new Date().toISOString().slice(0, 10)}. Sizes are gzip (level 9), with minified size in brackets. React itself is excluded from the runtime row but included in the app row.`,
  "",
  `| | ${rows.map((r) => r.app.name).join(" | ")} |`,
  `|---|${rows.map(() => "---").join("|")}|`,
  line("Library runtime only", (r) => r.runtime),
  line("Demo app initial JS (incl. React + en catalog)", (r) => r.initial),
  line("Lazy `pl` catalog chunk", (r) => r.locales.pl),
  line("Lazy `ar` catalog chunk", (r) => r.locales.ar),
  "",
  "Brotli: " +
    rows.map((r) => `${r.app.name} runtime ${kb(r.runtime.brotli)}, initial ${kb(r.initial.brotli)}`).join("; ") +
    ".",
  "",
].join("\n");

mkdirSync(join(root, "reports"), { recursive: true });
writeFileSync(join(root, "reports/bundle-size.md"), report);
console.log(`\n${report}`);
